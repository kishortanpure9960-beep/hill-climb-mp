// Builds the static client for hosts like Vercel:
//  - copies shared/ modules into public/shared so they are served as static files
//  - writes public/config.js with the game server address
//
// GAME_SERVER=wss://my-server.example.com node tools/build-static.js
import { mkdir, copyFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sharedDir = path.join(root, 'shared');
const outDir = path.join(root, 'public', 'shared');

await mkdir(outDir, { recursive: true });

const files = await readdir(sharedDir);
for (const file of files) {
  if (!file.endsWith('.js')) continue;
  await copyFile(path.join(sharedDir, file), path.join(outDir, file));
}

const server = process.env.GAME_SERVER || '';
await writeFile(
  path.join(root, 'public', 'config.js'),
  `// generated by tools/build-static.js\nwindow.HC_SERVER = ${JSON.stringify(server)};\n`
);

console.log(`static build ready (${files.length} shared modules) — game server: ${server || 'same origin'}`);
